"""Source-to-Gold lineage (ADR 0042): PostgreSQL table → Bronze → Silver → dbt models.

dbt's manifest already holds the Gold half of the graph (``depends_on`` between models and
sources). This module joins it to the Silver specs, which know each Silver table's source
contract, so one report answers "which source rows feed this Gold model, and who owns them".

Built offline from ``dbt parse`` output (``dbt/target/manifest.json``); no AWS access.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

from procurelake.ingestion.connectors.postgres_snapshot import SOURCE_SYSTEM as SNAPSHOT_SOURCE_SYSTEM
from procurelake.lakehouse.silver.spec import SilverTableSpec

# Bronze layouts of the operational tables: consistent snapshots (connector
# ``postgres_snapshot``, ADR 0023) and DMS full load + CDC, one ``load_id`` per dev/cdc stack
# (``modules/dms_s3_cdc`` bucket folder, ADR 0027). The contract's ``source_system`` names the
# database, not the Bronze prefix.
SNAPSHOT_ROOT = f"bronze/{SNAPSHOT_SOURCE_SYSTEM}/{{table}}/"
CDC_ROOT = "bronze/postgres_cdc/load_id=*/{schema}/{table}/"


@dataclass(frozen=True)
class SilverLineage:
    silver_table: str
    owner: str | None
    data_classification: str | None
    source_table: str | None  # schema.table in the operational database; None without a contract
    bronze_prefixes: tuple[str, ...]


@dataclass(frozen=True)
class GoldLineage:
    model: str
    owner: str | None
    data_classification: str | None
    inputs: tuple[str, ...]  # Gold models and Silver tables it reads, through staging/intermediate
    upstream_models: tuple[str, ...]  # every model it depends on, directly or not
    silver: tuple[SilverLineage, ...]  # every Silver table it depends on, directly or not


def _silver_lineage(table: str, specs_by_table: Mapping[str, SilverTableSpec]) -> SilverLineage:
    spec = specs_by_table.get(table)
    if spec is None:
        return SilverLineage(table, None, None, None, ())
    c = spec.contract
    fmt = {"schema": c.physical.schema_name, "table": c.physical.table}
    return SilverLineage(
        silver_table=table,
        owner=c.owner,
        data_classification=c.data_classification,
        source_table=f"{c.physical.schema_name}.{c.physical.table}",
        bronze_prefixes=(SNAPSHOT_ROOT.format(**fmt), CDC_ROOT.format(**fmt)),
    )


def gold_lineage(
    manifest: dict[str, Any],
    specs: Mapping[str, SilverTableSpec],
    gold_dirs: tuple[str, ...] = ("core", "marts"),
) -> list[GoldLineage]:
    """Lineage of every Gold model (a model under ``models/<gold_dir>/``), sorted by name."""
    nodes = manifest["nodes"]
    sources = manifest["sources"]
    specs_by_table = {s.silver_table: s for s in specs.values()}

    def is_gold(uid: str) -> bool:
        if nodes[uid]["resource_type"] != "model":
            return False
        parts = nodes[uid]["original_file_path"].split("/")  # models/<dir>/...
        return len(parts) >= 3 and parts[1] in gold_dirs

    def inputs(uid: str) -> set[str]:
        out: set[str] = set()
        for dep in nodes[uid]["depends_on"]["nodes"]:
            if dep in sources:
                out.add(sources[dep]["name"])
            elif dep in nodes and nodes[dep]["resource_type"] == "model":
                out |= {nodes[dep]["name"]} if is_gold(dep) else inputs(dep)
        return out

    def walk(uid: str, models: set[str], silver: set[str]) -> None:
        for dep in nodes[uid]["depends_on"]["nodes"]:
            if dep in sources:
                silver.add(sources[dep]["name"])
            elif dep in nodes and nodes[dep]["resource_type"] == "model" and nodes[dep]["name"] not in models:
                models.add(nodes[dep]["name"])
                walk(dep, models, silver)

    out = []
    for uid, node in nodes.items():
        if not is_gold(uid):
            continue
        models: set[str] = set()
        silver: set[str] = set()
        walk(uid, models, silver)
        meta = node["config"].get("meta") or node.get("meta") or {}
        out.append(
            GoldLineage(
                model=node["name"],
                owner=meta.get("owner"),
                data_classification=meta.get("data_classification"),
                inputs=tuple(sorted(inputs(uid))),
                upstream_models=tuple(sorted(models)),
                silver=tuple(_silver_lineage(t, specs_by_table) for t in sorted(silver)),
            )
        )
    return sorted(out, key=lambda g: g.model)


def to_markdown(lineage: list[GoldLineage]) -> str:
    """A Markdown report: a Mermaid graph (source → Silver → Gold) and one table per Gold model."""
    lines = [
        "# ProcureLake lineage: source to Gold",
        "",
        "Generated by `make lineage` from the dbt manifest and the Silver specs (ADR 0042). "
        "Do not edit by hand.",
        "",
        "```mermaid",
        "flowchart LR",
    ]
    edges: set[str] = set()
    for g in lineage:
        for s in g.silver:
            if s.source_table:
                edges.add(
                    f'  src_{s.source_table.replace(".", "_")}["{s.source_table}"] --> {s.silver_table}'
                )
        edges |= {f"  {i} --> {g.model}" for i in g.inputs}
    lines += sorted(edges)
    lines += ["```", ""]
    for g in lineage:
        lines += [
            f"## {g.model}",
            "",
            f"Owner: {g.owner or '(not set)'} · classification: {g.data_classification or '(not set)'}",
            "",
            f"Reads: {', '.join(g.inputs)}",
            "",
            f"Upstream models: {', '.join(g.upstream_models) or '(none)'}",
            "",
            "| Silver table | Owner | Classification | Source table | Bronze prefixes |",
            "|---|---|---|---|---|",
        ]
        for s in g.silver:
            prefixes = "<br>".join(f"`{p}`" for p in s.bronze_prefixes) or "(no source contract)"
            lines.append(
                f"| {s.silver_table} | {s.owner or '-'} | {s.data_classification or '-'} "
                f"| {s.source_table or '-'} | {prefixes} |"
            )
        lines.append("")
    return "\n".join(lines)
